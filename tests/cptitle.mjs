/* 🎯 คอลัมน์ CP — ตัดสินที่ "พาดหัว" อย่างเดียว ไม่ไปอ่านเนื้อข่าวแล้ว
 *
 * เจ้าของสั่ง 2 ก.ย. 2026 พร้อมภาพจากคอลัมน์ CP:
 *   "ตัดยังไงก็ไม่หมด คิดว่าเอาเฉพาะ keyword อยู่ในพาดหัวเลยดีกว่า ใน body ไม่เอาเลย"
 *
 * 2 ใบในภาพ — พาดหัวไม่มีชื่อเครือเลย แต่ชื่อเครือโผล่ในสรุป/เนื้อ:
 *   · "ทิสโก้เตือน 'กับดักอากาศธรรม' ชู 7 หุ้น Defensive รับมือความเสี่ยง"  ← ข่าวหุ้น ไล่ชื่อบริษัทเป็นพรืด
 *   · "'มท.4' ยันเหตุวิจารณ์สอบท้องถิ่นไม่จบแค่อลงชื่อ ชง 5 หน่วยงาน…"      ← ข่าวการเมือง
 *
 * ⚠️ ที่วัดคือ "โค้ดเดินทางไหน" ไม่ใช่ "เว็บจริงแสดงอะไร" — ยิงเข้าเว็บจริงจากที่นี่ไม่ได้
 *
 * รันด้วย: node cptitle.mjs
 */
import fs from "node:fs";
import { cpEvidence } from "../functions/api/_lib/noise.js";

let pass = 0, fail = 0;
const ok = (n, c, x = "") => { c ? (pass++, console.log("  ✅ " + n)) : (fail++, console.log("  ❌ " + n + (x ? " → " + x : ""))); };

const SRC = {
  trend: fs.readFileSync(new URL("../functions/api/trend/feeds.js", import.meta.url), "utf8"),
  ir: fs.readFileSync(new URL("../functions/api/ir/feeds.js", import.meta.url), "utf8"),
};

console.log("\n[1] 🎯 2 ใบจากภาพ — พาดหัวไม่มีชื่อเครือ = ต้องไม่ผ่านด่านแรก");
{
  const SHOT = [
    'ทิสโก้เตือน "กับดักอากาศธรรม" ชู 7 หุ้น Defensive รับมือความเสี่ยง - Kaohoon',
    "'มท.4' ยันเหตุวิจารณ์สอบท้องถิ่นไม่จบแค่อลงชื่อ ชง 5 หน่วยงานสาวลึกถึงต้นตอ-เส้นทางเงิน - เดลินิวส์",
  ];
  for (const t of SHOT)
    ok(`ไม่มีหลักฐานในพาดหัว: ${t.slice(0, 34)}…`, cpEvidence(t) === "", cpEvidence(t) || "(ว่าง)");

  // ⚠️ ทั้งคู่มีชื่อเครือใน "สรุป" — ของเดิมจึงไปอ่านเนื้อแล้วเจอ แล้วปล่อยผ่าน
  const SNIP = "ซีพี ออลล์ จำกัด (มหาชน) หรือ CPALL บริษัท เจริญโภคภัณฑ์อาหาร จำกัด (มหาชน) หรือ CPF";
  ok("พิสูจน์ต้นเหตุ: ชื่อเครืออยู่ในสรุปจริง", cpEvidence(SNIP) === "strong", cpEvidence(SNIP));
}

console.log("\n[2] 🚫 โค้ดต้องไม่ส่งคอลัมน์ CP ไปอ่านเนื้อข่าวอีกแล้ว");
for (const [name, s] of Object.entries(SRC)) {
  // ด่านของคอลัมน์ CP ต้องจบด้วย ok:false ไม่ใช่ ok:"body"
  ok(`${name}: ไม่มีชื่อเครือในพาดหัว = ตัดทันที`,
    /return \{ ok: false, why: "ไม่มีชื่อเครือ CP ในพาดหัว"/.test(s),
    (s.match(/return \{ ok: "?\w+"?, why: "ไม่มีชื่อเครือ CP ในพาดหัว"/) || ["ไม่เจอ"])[0]);
  ok(`${name}: 🚫 ไม่เหลือทางไปอ่านเนื้อของคอลัมน์ CP`,
    !/ok: "body", why: "ไม่มีชื่อเครือ CP/.test(s));
  // ⚠️ ชั้น AI ที่ยิงหลังอ่านเนื้อกลายเป็นโค้ดตาย ต้องถูกถอด ไม่ใช่ทิ้งไว้ให้เข้าใจผิดว่ายังทำงาน
  ok(`${name}: 🚫 ถอดชั้น AI ที่ผูกกับการอ่านเนื้อออกแล้ว`, !/const blind = toFetch/.test(s));
}

console.log("\n[3] 🚫 คอลัมน์ 'หัวข้อที่จับตามอง' ยังต้องอ่านเนื้อข่าวเหมือนเดิม");
{
  // เจ้าของเคยเจอ 20 ส.ค. 2026: ด่านอ่านเนื้อของคอลัมน์นี้พังเงียบ แล้วข่าวจริงหายไป 9 ใบ
  // ("วอนรัฐเร่งแก้ 'โรคกุ้ง' …") เพราะพาดหัวจากฟีดถูกตัดสั้นจนคำหลุดออกไป
  for (const [name, s] of Object.entries(SRC))
    ok(`${name}: คอลัมน์อื่นยังมีด่านอ่านเนื้อ`,
      /ok: "body", why: "ไม่อยู่ในพาดหัว\/เนื้อ"/.test(s));
}

console.log("\n[4] ✅ ข่าวจริงของเครือยังต้องเข้าคอลัมน์ได้");
{
  // ใบพวกนี้ชื่อเครืออยู่ในพาดหัว จึงผ่านตั้งแต่ด่านแรก ไม่ต้องพึ่งเนื้อข่าวอยู่แล้ว
  const KEEP = [
    "ซีพีเอฟ แจ้งผลประกอบการไตรมาส 2 กำไรโต 30%",
    "ซีพี แอ็กซ์ตร้า โชว์ผลงานครึ่งปีแรก",
    "เซเว่น อีเลฟเว่น ปรับราคาสินค้า",
    "ธนินท์ เจียรวนนท์ กล่าวปาฐกถาที่งานสัมมนา",
    "CP AXTRA เปิดตัว HAPPITAT",
  ];
  for (const t of KEEP) ok(`ยังผ่าน: ${t.slice(0, 30)}`, cpEvidence(t) === "strong", cpEvidence(t) || "(ว่าง)");

  // "CP" เดี่ยวๆ ในพาดหัว = weak → ยังส่งให้ AI อ่านพาดหัวตัดสิน (ไม่ได้ถูกตัดทิ้งไปด้วย)
  const WEAKCASE = "รฟท.นัดถก CP พรุ่งนี้ ชี้ขาดไฮสปีดเทรน 3 สนามบิน";
  ok("'CP' เดี่ยวในพาดหัว ยังไปต่อที่ชั้น AI ไม่ถูกตัดทิ้ง", cpEvidence(WEAKCASE) !== "", cpEvidence(WEAKCASE));
  for (const [name, s] of Object.entries(SRC))
    ok(`${name}: ชั้น AI สำหรับชื่อเครือกลางคำอื่น ยังอยู่`, /ok: "ai", why: "ai-weak-cp"/.test(s));
}

console.log("\n[5] สั่งตรวจของเก่าในคลังใหม่ ไม่งั้นใบที่ค้างอยู่ไม่หายไปไหน");
{
  // ใบที่ผ่านด่านเก่าแล้วติดธง vfy จะไม่ถูกตรวจซ้ำ — ต้องบวก VFY_VER ถึงจะโดนตรวจใหม่ทั้งคลัง
  for (const [name, s] of Object.entries(SRC)) {
    const v = s.match(/const VFY_VER = (\d+)/);
    ok(`${name}: bump VFY_VER แล้ว (≥ 7)`, v && Number(v[1]) >= 7, v ? v[1] : "-");
    const c = s.match(/const CACHE_VER = "(\d+)"/);
    ok(`${name}: bump CACHE_VER แล้ว`, c && Number(c[1]) >= (name === "trend" ? 85 : 79), c ? c[1] : "-");
  }
}

console.log(`\n${fail === 0 ? "✅" : "❌"} ผ่าน ${pass} · ตก ${fail}\n`);
process.exit(fail ? 1 : 0);
